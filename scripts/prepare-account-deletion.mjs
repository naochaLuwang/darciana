import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = resolve(root, 'supabase/functions/delete-account');
const entry = (await readFile(resolve(source, 'index.ts'), 'utf8')).replace(
  /^import \{ createDeleteAccountHandler \} from '\.\/handler\.mjs';\r?\n/m,
  '',
);
const handler = await readFile(resolve(source, 'handler.mjs'), 'utf8');
const { imports: mapping } = JSON.parse(await readFile(resolve(source, 'deno.json'), 'utf8'));
const imports = [];
const stripImports = (text) =>
  text.replace(/^import (.+) from ['"]([^'"]+)['"];\r?\n/gm, (_line, binding, original) => {
    const specifier = mapping[original] ?? original;
    if (!specifier.startsWith('npm:'))
      throw new Error(`Dashboard file must be self-contained; unexpected import: ${original}`);
    imports.push(`import ${binding} from '${specifier}';`);
    return '';
  });
const entryBody = stripImports(entry);
const handlerBody = stripImports(handler);
const output = `${imports.join('\n')}\n\n// Generated by node scripts/prepare-account-deletion.mjs.\n// Replace ALL of index.ts in the dashboard with this ENTIRE file.\n${handlerBody.trim()}\n\n${entryBody.trim()}\n`;
const directory = resolve(root, 'artifacts/account-deletion');
await mkdir(directory, { recursive: true });
await writeFile(resolve(directory, 'index.ts'), output);
console.log(
  'Prepared artifacts/account-deletion/index.ts with explicit npm imports and no local dependencies.',
);
